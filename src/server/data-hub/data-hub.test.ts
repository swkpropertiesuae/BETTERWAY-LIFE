test('xlsx template round-trips through the importer', async () => {
  const db = createTestDb();
  const admin = u(db, 'md@betterwaymortgages.com');
  const spec = specByNo(1)!;
  const buf = await writeXlsx('Data', spec.columns, [['B1', 'Emirates NBD', 'ACTIVE', 'portal', 'tariq', 'doc-1', '2026-11-01']]);
  assert.equal((await readXlsx(buf))[0][0], 'bank_id');
  const r = await importFile(db, admin, { specNo: 1, fileName: 'Bank_Master.xlsx', bytes: buf });
  assert.deepEqual([r.source, r.accepted, r.held, r.rejected], [1, 1, 0, 0]);
});

test('setup import: bad rows rejected, unsourced rows held and unused, new version supersedes, validity window honoured', async () => {
  const db = createTestDb();
  const admin = u(db, 'md@betterwaymortgages.com');
  const cols = specByNo(4)!.columns;
  const row = (id: string, o: Record<string, string> = {}) => cols.map((c) => ({ rule_id: id, max_ltv_pct: '80', max_dbr_pct: '50', effective_from: '2026-01-01', source_ref: 'CBUAE-1', approver: 'MD', ...o })[c as string] ?? '');
  const r = await importFile(db, admin, { specNo: 4, fileName: 'r.csv', bytes: csv(cols, [
    row('R1'), row('R2', { max_ltv_pct: '150' }), row('R3', { source_ref: '' }), row('R1'), row('R4', { effective_from: '2027-01-01' }), row('R5', { effective_from: '2026-02-01', effective_to: '2026-01-01' }),
  ]) });
  assert.deepEqual([r.source, r.accepted, r.held, r.rejected], [6, 2, 1, 3]); // R1 ok, R4 ok; R3 held; R2, dup R1, R5 rejected
  assert.deepEqual(activeRows(db, 4, '2026-06-01').map((x) => x.rule_id), ['R1']); // R4 not yet effective, R3 held
  await importFile(db, admin, { specNo: 4, fileName: 'r2.csv', bytes: csv(cols, [row('R1', { max_ltv_pct: '75' })]) });
  assert.equal(activeRows(db, 4, '2026-06-01').find((x) => x.rule_id === 'R1')!.max_ltv_pct, '75');
  assert.equal(activeRows(db, 4, '2026-06-01').filter((x) => x.rule_id === 'R1').length, 1);
});

test('migration import rejects duplicate external ids, missing columns and enforces roles + sign-off evidence', async () => {
  const db = createTestDb();
  const admin = u(db, 'md@betterwaymortgages.com');
  const cols = specByNo(16)!.columns;
  const row = (id: string) => cols.map((c) => (c === 'legacy_lead_id' ? id : c === 'captured_at' ? '16/11/2026' : c === 'email' ? 'a@b.co' : 'x'));
  await importFile(db, admin, { specNo: 16, fileName: 'a.csv', bytes: csv(cols, [row('L1')]) });
  const r2 = await importFile(db, admin, { specNo: 16, fileName: 'b.csv', bytes: csv(cols, [row('L1'), row('L2')]) });
  assert.deepEqual([r2.accepted, r2.rejected], [1, 1]);
  assert.equal((JSON.parse((db.prepare("SELECT data_json FROM data_rows WHERE external_id = 'L2'").get() as { data_json: string }).data_json) as Record<string, string>).captured_at, '2026-11-16');
  await assert.rejects(importFile(db, admin, { specNo: 16, fileName: 'c.csv', bytes: csv(['legacy_lead_id'], [['L3']]) }), /Missing columns/);
  await assert.rejects(importFile(db, u(db, 'reem.hr@betterwaymortgages.com'), { specNo: 16, fileName: 'd.csv', bytes: csv(cols, [row('L9')]) }), /not permitted/);
  await assert.rejects(importFile(db, admin, { specNo: 24, fileName: 'e.csv', bytes: csv(cols, []) }), /generated by the OS/);
  assert.throws(() => reviewBatch(db, admin, 1, ' '), /Evidence/);
});

