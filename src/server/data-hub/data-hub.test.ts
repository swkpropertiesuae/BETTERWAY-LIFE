test('quote: versioned, approved by advisor, required before underwriting; reason codes enforced when configured; 12 milestones', async () => {
  const db = createTestDb();
  const advisor = u(db, 'tariq.advisor@betterwaymortgages.com');
  const lead = db.prepare("INSERT INTO leads (contact_name, contact_phone, first_response_due_at, client_consent_logged_at) VALUES ('T','+971500000002', datetime('now'), datetime('now'))").run();
  const { dealId } = convertLeadToDeal(db, advisor, { leadId: Number(lead.lastInsertRowid), residencyType: 'EXPAT_RESIDENT', basicSalaryFils: 4_500_000, allowancesFils: 1_500_000, purchasePriceFils: 150_000_000, targetLoanFils: 100_000_000, tenureMonths: 300, emirate: 'dubai', communityName: 'Dubai Hills Estate' });
  db.prepare("UPDATE deals SET stage = 'DOC_COLLECTION' WHERE id = ?").run(dealId);

  assert.ok(getDealWorkflow(db, dealId).blockers.some((b) => b.includes('quote')));
  const q1 = saveQuote(db, advisor, dealId);
  const q2 = saveQuote(db, advisor, dealId);
  assert.deepEqual([q1.version, q2.version], [1, 2]);
  approveQuote(db, advisor, q2.id);
  assert.ok(!getDealWorkflow(db, dealId).blockers.some((b) => b.includes('quote')));
  assert.equal(milestonesFor(db, dealId)[2].state, 'done');
  db.prepare('UPDATE deals SET target_loan_fils = 90000000 WHERE id = ?').run(dealId);
  assert.throws(() => approveQuote(db, advisor, q1.id), /terms changed/);
  approveQuote(db, advisor, q1.id, 'Client agreed lower loan');
  assert.equal((db.prepare('SELECT status FROM deal_quotes WHERE id = ?').get(q2.id) as { status: string }).status, 'SUPERSEDED');

  // configured reason codes become mandatory
  const admin = u(db, 'md@betterwaymortgages.com');
  const c8 = specByNo(8)!.columns;
  await importFile(db, admin, { specNo: 8, fileName: 's.csv', bytes: csv(c8, [c8.map((c) => (c === 'stage_code' ? 'FACT_FIND' : c === 'sla_hours' ? '4' : c === 'reason_code' ? 'PRICE_TOO_HIGH' : 'x'))]) });
  assert.throws(() => applyException(db, advisor, dealId, 'WITHDRAW', { reason: 'x' }), /reason code/);
  applyException(db, advisor, dealId, 'WITHDRAW', { reason: 'x', reasonCode: 'PRICE_TOO_HIGH' });
  assert.equal(getDealWorkflow(db, dealId).stage, 'WITHDRAWN');
});
