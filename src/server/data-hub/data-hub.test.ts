const u = (db: ReturnType<typeof createTestDb>, e: string) => db.prepare('SELECT * FROM users WHERE email = ?').get(e) as UserRecord;
const csv = (cols: string[], rows: string[][]) => Buffer.from([cols.join(','), ...rows.map((r) => r.join(','))].join('\n'));

